const VISUAL_STORY_LOCALES = ["en", "zh-CN", "zh-TW"];
const VISUAL_STORY_STORAGE_KEY = "visualStory.locale";
const localeSelect = document.querySelector("#languageSelect");
function resolveLocale() {
  const param = new URLSearchParams(window.location.search).get("lang");
  if (param && VISUAL_STORY_LOCALES.includes(param)) return param;
  try {
    const saved = window.localStorage.getItem(VISUAL_STORY_STORAGE_KEY);
    if (VISUAL_STORY_LOCALES.includes(saved)) return saved;
  } catch (_error) { /* localStorage may be unavailable, e.g. file:// privacy mode */ }
  return "en";
}
function applyLocale(locale, persist=false) {
  const normalized = VISUAL_STORY_LOCALES.includes(locale) ? locale : "en";
  for (const el of document.querySelectorAll("[data-i18n]")) {
    const key=el.dataset.i18n;
    if (VISUAL_STORY_TRANSLATIONS[key]) el.textContent = VISUAL_STORY_TRANSLATIONS[key][normalized];
  }
  for (const el of document.querySelectorAll("[data-i18n-html]")) {
    const key=el.dataset.i18nHtml;
    // All values come from the static developer-owned catalog, never user input.
    if (VISUAL_STORY_TRANSLATIONS[key]) el.innerHTML = VISUAL_STORY_TRANSLATIONS[key][normalized];
  }
  for (const el of document.querySelectorAll("[data-i18n-aria-label]")) {
    const key=el.dataset.i18nAriaLabel;
    if (VISUAL_STORY_TRANSLATIONS[key]) el.setAttribute("aria-label", VISUAL_STORY_TRANSLATIONS[key][normalized]);
  }
  for (const el of document.querySelectorAll("[data-i18n-content]")) {
    const key=el.dataset.i18nContent;
    if (VISUAL_STORY_TRANSLATIONS[key]) el.setAttribute("content", VISUAL_STORY_TRANSLATIONS[key][normalized]);
  }
  document.documentElement.lang = normalized;
  if (localeSelect) localeSelect.value = normalized;
  if (persist) {
    try {window.localStorage.setItem(VISUAL_STORY_STORAGE_KEY,normalized);} catch (_error) {/* Optional persistence */}
  }
  // The menu label is state-dependent and may be open after translation.
  const navToggle = document.querySelector("#navToggle");
  if (navToggle) {
    const expanded=navToggle.getAttribute("aria-expanded")==="true";
    navToggle.setAttribute("aria-label",VISUAL_STORY_TRANSLATIONS[expanded ? "closeMenu" : "openMenu"][normalized]);
  }
}
let currentLocale = resolveLocale();
applyLocale(currentLocale);
localeSelect?.addEventListener("change",(event)=>{
  currentLocale = event.target.value;
  applyLocale(currentLocale,true);
});
window.VisualStoryI18n = { getLocale:()=>currentLocale, translate:(key)=>VISUAL_STORY_TRANSLATIONS[key]?.[currentLocale] || key };
